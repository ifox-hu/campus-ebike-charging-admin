// Browser smoke test of the built static site, including repository subpath.
const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs'),path=require('node:path')
const base=process.env.PAGES_QA_URL||'http://127.0.0.1:5207/campus-ebike-charging/'
const expectAmap=process.env.PAGES_EXPECT_AMAP==='true'
async function main(){
 const browser=await chromium.launch({channel:'msedge',headless:true})
 try{
  const page=await browser.newPage({viewport:{width:1600,height:1100}}),errors=[],apiRequests=[],failedAssets=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('request',r=>{if(new URL(r.url()).pathname.startsWith('/api/'))apiRequests.push(r.url())})
  page.on('response',r=>{if(r.status()>=400&&/\.(js|css)(\?|$)/.test(r.url()))failedAssets.push({url:r.url(),status:r.status()})})
  const mapTile=expectAmap?page.waitForResponse(r=>{const u=new URL(r.url());return /(^|\.)amap\.com$/.test(u.hostname)&&u.pathname.startsWith('/tile/')&&r.status()===200},{timeout:35000}):null
  await page.goto(base+'#/dashboard')
  await page.getByRole('heading',{name:'在线演示登录',exact:true}).waitFor()
  assert.equal(await page.locator('.metric-card').count(),0)
  const screenshots=path.resolve(__dirname,'artifacts');fs.mkdirSync(screenshots,{recursive:true})
  await page.screenshot({path:path.join(screenshots,'pages-login.png')})
  await page.setViewportSize({width:390,height:844})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile login must fit viewport')
  await page.screenshot({path:path.join(screenshots,'pages-login-mobile.png')})
  await page.setViewportSize({width:1600,height:1100})
  await page.locator('input[autocomplete=username]').fill('demo')
  await page.locator('input[autocomplete=current-password]').fill('incorrect')
  await page.locator('.login-submit').click()
  await page.getByRole('alert').filter({hasText:'演示账号或密码不正确'}).waitFor()
  assert.equal(await page.locator('.metric-card').count(),0)
  await page.getByRole('button',{name:'填入演示账号',exact:true}).click()
  await page.getByRole('button',{name:'显示密码',exact:true}).click()
  assert.equal(await page.locator('input[autocomplete=current-password]').getAttribute('type'),'text')
  await page.getByRole('button',{name:'隐藏密码',exact:true}).click()
  await page.locator('input[type=checkbox]').check()
  await page.locator('.login-submit').click()
  await page.locator('.metric-card').first().waitFor()
  assert.equal(await page.locator('.metric-card').count(),7)
  assert.equal(await page.locator('.login-submit').count(),0)
  if(expectAmap){
   await page.locator('.map-runtime.ready').waitFor({timeout:35000})
   assert.equal(await page.locator('.map-diagram').count(),0,'在线演示必须显示真实高德底图')
   assert.equal(await page.locator('.amap-stage .station-marker').count(),16)
   assert.equal(await page.evaluate(()=>!!window.AMap?.Map),true)
   await (await mapTile).finished()
   await page.waitForTimeout(800)
  }else{
   await page.locator('.map-diagram').waitFor()
   assert.equal(await page.locator('.map-diagram .station-marker').count(),16)
  }
  await page.screenshot({path:path.join(screenshots,'pages-dashboard.png')})
  await page.locator('.navigation .nav-item').filter({hasText:'设备与插座'}).click()
  await page.getByLabel('筛选站点',{exact:true}).selectOption('ST04')
  await page.waitForFunction(()=>document.querySelector('.layout-summary strong')?.textContent==='西区八公寓北侧示例站')
  assert.equal(await page.locator('.physical-row').count(),3)
  assert.deepEqual(await page.locator('.physical-row').evaluateAll(rows=>rows.map(row=>row.querySelectorAll('.physical-device').length)),[9,11,8])
  await page.locator('.management-glass').screenshot({path:path.join(screenshots,'station-layout.png')})
  await page.getByRole('button',{name:'管理员账号菜单',exact:true}).click()
  assert.equal(await page.getByRole('button',{name:'修改密码',exact:true}).count(),0)
  await page.getByRole('button',{name:'显示设置',exact:true}).click()
  await page.locator('.account-form label').filter({hasText:'全局字号'}).locator('select').selectOption('large')
  await page.locator('.account-form label').filter({hasText:'表格密度'}).locator('select').selectOption('compact')
  await page.locator('.account-form').getByRole('button',{name:'保存',exact:true}).click()
  await page.reload();await page.locator('.platform').waitFor()
  assert.equal(await page.locator('html').getAttribute('data-font-size'),'large')
  assert.equal(await page.locator('html').getAttribute('data-density'),'compact')
  await page.getByRole('button',{name:'通知中心',exact:true}).click()
  await page.getByRole('button',{name:'全部已读',exact:true}).click()
  await page.getByRole('button',{name:'全部已读',exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:'全部已读',exact:true}).isEnabled(),false)
  await page.getByRole('button',{name:'管理员账号菜单',exact:true}).click()
  await page.getByRole('button',{name:'退出登录',exact:true}).click()
  await page.getByRole('heading',{name:'在线演示登录',exact:true}).waitFor()
  await page.reload();await page.getByRole('heading',{name:'在线演示登录',exact:true}).waitFor()
  assert.equal(await page.locator('input[autocomplete=username]').inputValue(),'demo')
  assert.equal(await page.locator('input[autocomplete=current-password]').inputValue(),'')
  assert.ok(await page.evaluate(()=>!JSON.stringify({...localStorage,...sessionStorage}).includes('Demo@123456')))
  await page.getByRole('button',{name:'填入演示账号',exact:true}).click()
  await page.locator('.login-submit').click()
  await page.locator('.platform').waitFor()
  await page.locator('.navigation .nav-item').filter({hasText:'运营概览'}).click()
  await page.locator('.metric-card').first().waitFor()
  assert.deepEqual(apiRequests,[])
  assert.deepEqual(failedAssets,[])
  assert.deepEqual(errors,[])
  const proof={base,mapMode:expectAmap?'amap':'diagram',realMapTileVerified:expectAmap,loginRequired:true,invalidCredentialsRejected:true,sessionSurvivesReload:true,logoutSurvivesReload:true,passwordNotStored:true,mobileLoginFits:true,repoSubpathAssets:true,noBackendRequests:true,variedRows:true,preferencesSurviveReload:true,notificationsWork:true,demoReentry:true,pageErrors:errors}
  fs.writeFileSync(path.join(__dirname,'pages-verification.json'),JSON.stringify(proof,null,2)+'\n')
  console.log(JSON.stringify(proof,null,2))
 }finally{await browser.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
